/**
 * Упътвания с прости думи: как се прави всеки елемент стъпка по стъпка,
 * какво да не забравиш, как идва бетонът и как се чете чертеж.
 *
 * Това е обща практика. Проектът и техническият ръководител на обекта винаги са с предимство.
 */
import { anchorLength, lapLength, type CalcSettings, type Element } from './calc';
import { fmt } from './labels';

export type GuideStep = { title: string; do: string[]; dontForget?: string[] };

const cm = (m: number) => `${fmt(m * 100, 0)} см`;

export function buildGuide(e: Element, s: CalcSettings): GuideStep[] {
  const cover = `${fmt(s.cover)} см`;
  switch (e.type) {
    case 'column':
      return [
        {
          title: 'Надлъжните пръти',
          do: [
            `Слагаш ${e.bars.n} пръта Ø${e.bars.d}: по един във всеки ъгъл, останалите на равни разстояния.`,
            `Долу се застъпват с шишовете, които стърчат от долния етаж или от основата — поне ${cm(lapLength(e.bars.d, s))}.`,
            `Горе оставяш да стърчат ${cm(lapLength(e.bars.d, s))} над плочата, за следващия етаж.`,
          ],
          dontForget: ['Прътите се връзват с тел за биглите на всяко пресичане в ъглите.'],
        },
        {
          title: 'Биглите (стремената)',
          do: [
            `Бигли Ø${e.stirrup.d} през ${e.stirrup.s} см по цялата височина.`,
            'Куките на биглите се огъват на 135° и влизат навътре в колоната.',
            'Куките се редуват — всяка следваща бигла е с куката в друг ъгъл.',
          ],
          dontForget: ['Виж в чертежа дали биглите се сгъстяват горе и долу, до плочата и гредите — често е така.'],
        },
        {
          title: 'Дистанционери и кофраж',
          do: [
            `Слагаш дистанционери (пластмасови колелца) за покритие ${cover} — по 3–4 на всяка страна.`,
            'Кофражът се намазва с кофражно масло, после се затваря около армировката.',
            'Проверяваш с либела или отвес, че е вертикален в двете посоки, и го подпираш.',
          ],
          dontForget: ['Долу почисти от тел, дърво и боклуци, преди да затвориш кофража.', 'Кофражът да е плътен — бетонното мляко изтича през цепнатините.'],
        },
        {
          title: 'Бетонът',
          do: [
            `Бетон ${e.concreteClass}. Сипваш на пластове по около 50 см и вибрираш всеки пласт.`,
            'Не пускай бетона отвисоко (повече от 1,5–2 м) — разслоява се. Ползвай ръкав или улей.',
            'Поддържай бетона влажен поне 7 дни.',
          ],
          dontForget: ['Не се добавя вода в бетона на обекта.', 'Кога се маха кофражът — решава техническият ръководител.'],
        },
      ];
    case 'beam':
      return [
        {
          title: 'Долните и горните пръти',
          do: [
            `Долу: ${e.bottom.n} пръта Ø${e.bottom.d}. ${e.top.n > 0 ? `Горе: ${e.top.n} пръта Ø${e.top.d}.` : 'Горе няма пръти по проект.'}`,
            `Прътите влизат в колоните поне ${cm(anchorLength(e.bottom.d, s))} (анкериране).`,
          ],
          dontForget: ['Долните пръти носят най-много — никога не ги прекъсвай по средата на гредата без снаждане.'],
        },
        {
          title: 'Биглите (стремената)',
          do: [
            `Бигли Ø${e.stirrup.d} през ${e.stirrup.s} см по цялата дължина.`,
            'Куките на 135°, отгоре, редуват се наляво и надясно.',
            'Прътите се връзват за всяка бигла в ъглите.',
          ],
          dontForget: ['Виж в чертежа дали биглите се сгъстяват до колоните.'],
        },
        {
          title: 'Кофраж и подпори',
          do: [
            `Дистанционери отдолу и отстрани — покритие ${cover}.`,
            'Дъното на кофража се подпира плътно, подпорите стъпват на здрава основа.',
            'Горният ръб на кофража е на котата от чертежа — провери с нивелир.',
          ],
          dontForget: ['Подпорите се махат най-късно — чак когато техническият ръководител разреши.'],
        },
        {
          title: 'Бетонът',
          do: [`Бетон ${e.concreteClass}, обикновено заедно с плочата.`, 'Вибрираш добре между прътите — там най-лесно остават кухини.'],
          dontForget: ['Не се добавя вода в бетона на обекта.'],
        },
      ];
    case 'slab':
      return [
        {
          title: 'Кофраж и подпори',
          do: [
            `Кофражът е равен и на котата от чертежа. Плоча ${fmt(e.lx)} × ${fmt(e.ly)} м, дебела ${e.t} см.`,
            'Подпорите — на разстоянията, които казва кофражната система, и стъпват на здраво.',
            'Кофражът се намазва с кофражно масло.',
          ],
          dontForget: e.openings > 0 ? [`Остави отворите от чертежа (общо ${fmt(e.openings)} м²) — после не се реже бетон.`] : ['Провери за отвори в чертежа — комини, стълби, шахти.'],
        },
        {
          title: 'Долната мрежа',
          do: [
            `Дистанционери за покритие ${cover}, после долна мрежа Ø${e.bottom.d} през ${e.bottom.s} см в двете посоки.`,
            'Прътите по дългата страна обикновено са отдолу — виж чертежа.',
            'Връзваш пресичанията с тел (поне през едно).',
          ],
          dontForget: ['Сега се слагат тръбите за ток и вода, и гилзите за канала.'],
        },
        {
          title: e.top ? 'Горната мрежа' : 'Проверка преди бетона',
          do: e.top
            ? [
                `Столчета (кобилици), после горна мрежа Ø${e.top.d} през ${e.top.s} см.`,
                'Столчетата са достатъчно, за да не се смачка мрежата, когато се ходи по нея.',
              ]
            : ['Проверяваш размери, покритие, снаждания и дали всичко е вързано.'],
          dontForget: ['Преди бетона армировката се приема от надзора и техническия ръководител (акт за скрити работи).'],
        },
        {
          title: 'Бетонът',
          do: [
            `Бетон ${e.concreteClass}, обикновено с помпа. Започваш от най-далечния край.`,
            'Вибрираш с иглен вибратор и изравняваш с мастар до котата.',
            'Поливаш или покриваш с найлон — плочата да е влажна поне 7 дни.',
          ],
          dontForget: ['Не ходи по плочата първото денонощие.', 'При студ (под 5 °C) или жега — питай техническия ръководител за мерки.'],
        },
      ];
    case 'wall':
      return [
        {
          title: 'Вертикалните пръти',
          do: [
            `Вертикални Ø${e.vertical.d} през ${e.vertical.s} см — от двете страни на стената.`,
            `Застъпват се с шишовете от долу поне ${cm(lapLength(e.vertical.d, s))}.`,
          ],
        },
        {
          title: 'Хоризонталните пръти',
          do: [`Хоризонтални Ø${e.horizontal.d} през ${e.horizontal.s} см от двете страни.`, 'Двете мрежи се свързват с фиби — виж чертежа колко на м².'],
        },
        {
          title: 'Кофраж',
          do: [`Дистанционери — покритие ${cover}.`, 'Кофраж от двете страни, стегнат с шпилки, вертикален.'],
          dontForget: ['Остави отворите за врати и тръби, ако има.'],
        },
        {
          title: 'Бетонът',
          do: [`Бетон ${e.concreteClass}, на пластове по около 50 см, всеки пласт се вибрира.`],
          dontForget: ['Не пускай бетона отвисоко — ползвай ръкав.'],
        },
      ];
    case 'stair':
      return [
        {
          title: 'Кофраж на рамото',
          do: [`Наклонен кофраж, отгоре — чела за ${e.steps} стъпала.`, 'Всички стъпала да са еднакво високи — проверява се с метър.'],
        },
        {
          title: 'Главните пръти',
          do: [`Главни пръти Ø${e.main.d} през ${e.main.s} см по наклона.`, 'Горе и долу влизат в плочата или гредата — анкерират се.'],
        },
        {
          title: 'Разпределителните пръти',
          do: [`Разпределителни Ø${e.dist.d} през ${e.dist.s} см напречно, върху главните.`, `Дистанционери — покритие ${cover}.`],
        },
        {
          title: 'Бетонът',
          do: [`Бетон ${e.concreteClass}. Бетонира се отдолу нагоре.`, 'Стъпалата се оформят с мистрия, преди бетонът да стегне.'],
        },
      ];
    case 'masonry':
      return [
        {
          title: 'Хидроизолация',
          do: ['Под първия ред се слага хидроизолация — пази стената от влагата отдолу.'],
        },
        {
          title: 'Първият ред',
          do: ['Първият ред е най-важен: на разтвор, изравнен с нивелир, точно по конец.'],
          dontForget: ['Ако първият ред е крив, цялата стена ще е крива.'],
        },
        {
          title: 'Зидането',
          do: [
            'Фугите се разминават с поне половин тухла.',
            'Проверяваш с отвес и либела на всеки 2–3 реда.',
            'Над вратите и прозорците — щурц, опрян поне 20–25 см от всяка страна (виж указанията на производителя).',
          ],
        },
      ];
  }
}

